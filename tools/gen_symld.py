#!/usr/bin/env python3
"""Generate a linker script that PROVIDEs the firmware's symbols.

Reads the symbol table of the reconstructed device ELF (`app.rebuilt.elf`)
and emits `PROVIDE(name = 0xADDR);` for every named function/data symbol. Link
your injected code against the resulting `.ld` and calls to existing firmware /
maskrom routines (memcpy, LZ4_*, os_*, matched app funcs, ...) resolve to their
real addresses.

Usage:
    python3 tools/gen_symld.py --elf work/app.rebuilt.elf -o inject/app.ld
"""

import os
import re
import sys
import argparse
from elf import Elf

CODE_BASE = 0x1e00120
# ld symbol names: a C identifier. 
IDENT = re.compile(r'^[A-Za-z_][A-Za-z0-9_]*$')

# On a name clash the app's own copy keeps the plain name (the app links its own
# os_task_create/main/... and injected app code should call those); the colliding
# maskrom symbol is kept too but renamed `ROM_<name>` so both remain reachable.
# ROM-only routines (memcpy, LZ4_*, WOLA*, ...) keep their plain name.
ROM_SECTIONS = ('.rom_code', '.nul_space')

def load_symbols(elf):
    """Return sorted [(name, vaddr)] of identifier-named symbols in real
    sections. A maskrom symbol whose name collides with an app symbol is
    renamed `ROM_<name>`; a residual same-name clash keeps the first (reported)."""
    raw = []           # (name, vaddr, is_rom), in table order

    rom_sections = [
        elf.named_sections.get('.rom_code'), elf.named_sections.get('.nul_space')
    ]

    for name, vaddr in elf.symbols:
        if not IDENT.match(name):
            continue

        is_rom = False

        for sect in rom_sections:
            if sect and vaddr >= sect.sh_addr and vaddr < sect.sh_addr + sect.sh_size:
                is_rom = True

        if vaddr == 0:
            continue
        if is_rom: # shift ROM addresses to the mirrored area
            vaddr += 0x2000000
        raw.append((name, vaddr, is_rom))

    app_names = {n for n, _, is_rom in raw if not is_rom}
    syms = {}          # final name -> vaddr
    conflicts = []
    for name, vaddr, is_rom in raw:
        key = 'ROM_' + name if (is_rom and name in app_names) else name
        prev = syms.get(key)
        if prev is None:
            syms[key] = vaddr
        elif prev != vaddr:
            conflicts.append((key, prev, vaddr))
    for name, a0, a1 in conflicts:
        print("warn: %s at %#x and %#x — kept %#x" % (name, a0, a1, a0),
              file=sys.stderr)
    return sorted(syms.items(), key=lambda kv: kv[1])

def emit(syms):
    L = []
    L.append("/* Auto-generated by gen_symld.py */")
    L.append("")
    for name, vaddr in syms:
        L.append("PROVIDE(%s = %#x);" % (name, vaddr))
    L.append("")
    return "\n".join(L)


def main():
    p = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--elf", required=True, help="symbol source ELF")
    p.add_argument("-o", "--out", default=None, help="output .ld path (default: stdout)")
    args = p.parse_args()

    elf = Elf(open(args.elf, 'rb').read())

    syms = load_symbols(elf)
    text = emit(syms)

    if args.out:
        with open(args.out, "w") as f:
            f.write(text + "\n")

    else:
        sys.stdout.write(text + "\n")


if __name__ == "__main__":
    main()
